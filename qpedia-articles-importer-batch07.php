/**
 * ۳) برگرداندن شناسهٔ دسته در quantum_category (ساخت در صورت نبود).
 */
function qpai_term_id( $slug ) {
	$slug = sanitize_title( $slug );
	if ( '' === $slug ) { return 0; }
	$term = get_term_by( 'slug', $slug, 'quantum_category' );
	if ( $term && ! is_wp_error( $term ) ) {
		return (int) $term->term_id;
	}
	$map  = qpai_cat_map();
	$name = isset( $map[ $slug ] ) ? $map[ $slug ] : $slug;
	$r    = wp_insert_term( $name, 'quantum_category', array( 'slug' => $slug ) );
	if ( is_wp_error( $r ) ) {
		$data = $r->get_error_data();
		if ( isset( $data['term_exists'] ) ) {
			return (int) $data['term_exists'];
		}
		return 0;
	}
	return (int) $r['term_id'];
}

/**
 * ۴) پیدا کردن شناسهٔ کاربر برای نویسنده؛ در نبود، کاربر جاری یا ۱.
 */
function qpai_author_id( $name ) {
	$name = trim( (string) $name );
	if ( '' !== $name ) {
		$slugs   = array();
		$slugs[] = sanitize_title( $name );
		$slugs[] = str_replace( '-', '', sanitize_title( $name ) );
		foreach ( $slugs as $s ) {
			if ( '' === $s ) { continue; }
			$u = get_user_by( 'slug', $s );
			if ( $u ) { return (int) $u->ID; }
			$u = get_user_by( 'login', $s );
			if ( $u ) { return (int) $u->ID; }
		}
		$users = get_users( array( 'search' => '*' . $name . '*', 'number' => 1 ) );
		if ( ! empty( $users ) ) { return (int) $users[0]->ID; }
	}
	$current = get_current_user_id();
	return $current ? $current : 1;
}

